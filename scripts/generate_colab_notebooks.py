def build_cell(cell_type: str, source_lines: list) -> dict:
    """Helper to construct notebook cell dict."""
    formatted_source = [line + "\n" for line in source_lines[:-1]]
    if source_lines:
        formatted_source.append(source_lines[-1])
    return {
        "cell_type": cell_type,
        "metadata": {},
        "outputs": [] if cell_type == "code" else None,
        "execution_count": None if cell_type == "code" else None,
        "source": formatted_source,
    }


def make_notebook(cells: list) -> dict:
    return {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {
                "gpuType": "T4",
                "provenance": []
            },
            "language_info": {
                "name": "python",
                "version": "3.10.12"
            }
        },
        "nbformat": 4,
        "nbformat_minor": 2,
    }


